import assert from 'node:assert/strict';
import { chromium, firefox } from 'playwright';
import { hostBuild } from './test-host.mjs';

const host = await hostBuild();
const browser = await ({ chromium, firefox })[process.env.TUNO_BROWSER || 'chromium'].launch();
try {
  for (const width of [320, 375, 640, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 812 }, serviceWorkers: 'block' });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(new URL('/rhythm/', host.url).href);
    const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('tuno.rhythm-walk.preferences.v1')).generation);
    let original = await read();
    await page.locator('.count-slot').first().focus(); await page.keyboard.press('1');
    const answer = await page.locator('.count-slot').first().textContent();
    assert.equal(answer, '1');
    const music = () => page.locator('.passage g[data-event]').evaluateAll(nodes => nodes.map(n => [n.dataset.value, n.dataset.kind, n.dataset.dots, n.dataset.start, n.dataset.duration]));
    const passage = await music();
    const exerciseId = () => page.locator('.passage').getAttribute('data-exercise-id');
    const originalId = await exerciseId();
    const dialog = page.getByRole('dialog', { name: 'Choose rhythms', exact: true });
    const open = () => page.getByRole('button', { name: 'Choose rhythms', exact: true }).click();
    const use = () => dialog.getByRole('button', { name: 'Use preset', exact: true }).click();
    const uno = () => dialog.getByRole('tab', { name: 'Uno’s Choice', exact: true }).click();
    await open(); await use();
    assert.equal(await exerciseId(), originalId, 'accepting unchanged default settings retains the exercise');
    assert.equal(await page.locator('.count-slot').first().textContent(), answer);
    assert.doesNotMatch(await page.locator('.exercise-summary').textContent(), /Pending settings/);
    original = await read();
    await open(); await uno();
    assert.equal(await dialog.locator('.rhythm-preset-card').count(), 5);
    const boxes = await dialog.locator('.rhythm-preset-card').evaluateAll(nodes => nodes.map(n => { const r=n.getBoundingClientRect(); return { x:r.x, right:r.right, y:r.y, bottom:r.bottom }; }));
    assert.ok(boxes.every((b, i) => b.x === boxes[0].x && b.right === boxes[0].right && (!i || b.y >= boxes[i-1].bottom)), 'one column at every width');
    assert.equal(await dialog.evaluate(d => d.scrollWidth <= d.clientWidth + 1), true);
    await dialog.getByRole('button', { name: 'Uno3', exact: true }).click();
    assert.deepEqual(await read(), original, 'selection remains a draft');
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.deepEqual(await read(), original, 'Cancel discards selection');
    assert.deepEqual(await music(), passage, 'Cancel preserves the score');
    assert.equal(await page.locator('.count-slot').first().textContent(), answer, 'Cancel preserves the answer');
    await open(); await uno();
    await dialog.getByRole('button', { name: 'Uno3', exact: true }).click(); await use();
    assert.equal((await read()).teachingPreset.id, 'uno-3');
    assert.equal((await read()).teachingPreset.customized, false);
    assert.notEqual(await exerciseId(), originalId, 'Use preset immediately generates a new exercise');
    assert.equal(await page.locator('.count-slot').first().textContent(), '·', 'new exercise clears the prior answer');
    assert.match(await page.locator('.exercise-summary').textContent(), /Current exercise: Uno3/);
    assert.doesNotMatch(await page.locator('.exercise-summary').textContent(), /Pending settings/);
    const appliedId = await exerciseId();
    await page.locator('.count-slot').first().focus(); await page.keyboard.press('1');
    await open(); await use();
    assert.equal(await exerciseId(), appliedId, 'accepting unchanged settings retains the exercise');
    assert.equal(await page.locator('.count-slot').first().textContent(), answer);
    await open();
    assert.equal(await dialog.getByRole('button', { name: 'Uno3', exact: true }).getAttribute('aria-pressed'), 'true');
    await dialog.getByRole('button', { name: 'Customize Uno4', exact: true }).click();
    assert.equal(await dialog.getByRole('tab', { name: 'Custom', exact: true }).getAttribute('aria-selected'), 'true');
    assert.match(await dialog.locator('.rhythm-preset-panel > .setting-hint').textContent(), /Based on Uno4/);
    assert.equal(await dialog.locator('[data-setting="ties"]').isChecked(), true);
    await dialog.locator('[data-setting="ties"]').uncheck();
    await page.keyboard.press('Escape');
    assert.equal((await read()).teachingPreset.id, 'uno-3');
    assert.equal(await exerciseId(), appliedId, 'Escape preserves the exercise');
    assert.equal(await page.locator('.count-slot').first().textContent(), answer);
    await open();
    await dialog.getByRole('tab', { name: 'UIL Sight Reading', exact: true }).click();
    assert.equal(await dialog.locator('.rhythm-preset-card').count(), 4);
    const generalFigures = await dialog.locator('[data-preset-id="uil-1"] .rhythm-preset-symbol').count();
    await dialog.getByRole('combobox', { name: 'UIL instrument scope', exact: true }).selectOption('percussion');
    assert.ok(await dialog.locator('[data-preset-id="uil-1"] .rhythm-preset-symbol').count() > generalFigures);
    await dialog.getByRole('button', { name: 'UIL I', exact: true }).click(); await use();
    assert.equal((await read()).teachingPreset.scope, 'percussion');
    await open();
    await dialog.getByRole('tab', { name: 'Custom', exact: true }).click();
    await dialog.locator('[data-meter]:checked').uncheck();
    assert.equal(await dialog.getByRole('button', { name: 'Use preset', exact: true }).isDisabled(), true);
    await dialog.getByRole('button', { name: 'Cancel rhythm selection', exact: true }).click();
    assert.equal((await read()).teachingPreset.customized, false);
    await page.reload();
    assert.equal((await read()).teachingPreset.id, 'uil-1');
    await open();
    assert.equal(await dialog.getByRole('combobox', { name: 'UIL instrument scope', exact: true }).inputValue(), 'percussion');
    await dialog.getByRole('tab', { name: 'Custom', exact: true }).focus();
    await page.keyboard.press('Home');
    assert.equal(await dialog.getByRole('tab', { name: 'Uno’s Choice', exact: true }).getAttribute('aria-selected'), 'true');
    assert.deepEqual(errors, []);
    await page.close(); console.log(`Preset picker passed at ${width}px`);
  }
} finally { await browser.close(); await host.close(); }
