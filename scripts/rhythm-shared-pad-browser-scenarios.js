/** Focused scenarios for the native T3 preview, including same-origin narrow frames. */
window.runSharedPadBrowserScenarios = function (w = window) {
  const d = w.document;
  let assertions = 0;
  const assert = (value, message) => { if (!value) throw new Error(message); assertions++; };
  const q = selector => d.querySelector(selector);
  const choose = (control, value) => { control.value = value; control.dispatchEvent(new w.Event('change', { bubbles: true })); };
  const key = (target, value, shiftKey = false) => target.dispatchEvent(new w.KeyboardEvent('keydown', { key: value, shiftKey, bubbles: true, cancelable: true }));
  const palette = () => q('.count-palette:not([hidden])');
  const slot = index => q('[data-measure="1"]').querySelectorAll('.count-slot')[index];
  const control = name => [...d.querySelectorAll('button')].find(b => b.textContent === name);
  choose(q('select[aria-label="Mode"]'), 'both');
  choose(q('[data-preset]'), 'half-rest');
  const exercise = q('.passage').dataset.exerciseId;
  slot(0).click();
  assert(palette() && w.getComputedStyle(palette()).position === 'static', 'Counting palette is docked below the score');
  assert(palette().closest('.shared-interaction'), 'Counting and performance share one surface');
  assert(d.querySelectorAll('.count-palette:not([hidden])').length === 1, 'Only one measure palette is visible');
  palette().querySelector('[data-symbol="1"]').click();
  assert(slot(0).textContent === '1' && slot(2).getAttribute('aria-pressed') === 'true', 'Palette entry commits and advances');
  slot(0).click(); palette().querySelector('[aria-label="Start rest pair"]').click();
  assert([...q('.count-palette-host').querySelectorAll('.endpoint-prompt')].some(p => !p.hidden && p.textContent.includes('rest ends')), 'Rest endpoint instruction appears in the palette');
  slot(2).click();
  assert(slot(0).getAttribute('aria-label').includes('parenthesized') && slot(2).getAttribute('aria-label').includes('parenthesized'), 'Count box closes the rest pair');
  slot(0).click(); palette().querySelector('[aria-label="Start duration line"]').click(); slot(2).click();
  assert(q('.duration-line'), 'Count box closes the duration line');
  control('Perform').click();
  assert(!q('.tap-response').hidden && q('.count-palette-host').hidden, 'Perform shows the pad instead of the palette');
  assert(q('.performance-setup').contains(q('.score-tempo')) && q('.performance-setup').contains(q('[data-setting="how-to-play"]')), 'Tempo and play style are contextual performance setup');
  assert(q('.performance-setup input[type="checkbox"]'), 'Metronome is beside the pad');
  assert(slot(0).textContent === '1' && q('.rest-group') && q('.duration-line'), 'Switching retains the counting response');
  slot(4).click();
  assert(q('.tap-response').hidden && !q('.count-palette-host').hidden && palette(), 'Selecting a count returns to Counts');
  control('Check').click();
  assert(q('.tap-response').hidden, 'Check does not switch to Perform');
  slot(6).click(); key(slot(6), '=');
  assert(slot(6).textContent === '&', 'Equals remains the unshifted plus alias');
  slot(0).click(); key(slot(0), 'l'); slot(2).click(); key(slot(2), 'i');
  assert(slot(0).textContent === 'la' && slot(2).textContent === 'li', 'Single-key la/li entry remains intact');
  choose(q('select[aria-label="Mode"]'), 'tap');
  assert(!q('.tap-response').hidden && q('.count-palette-host').hidden && q('.interaction-selector').hidden, 'Tap mode shows only performance');
  choose(q('select[aria-label="Mode"]'), 'write');
  assert(q('.tap-response').hidden && !q('.count-palette-host').hidden && q('.interaction-selector').hidden, 'Write mode shows only counting');
  assert(q('.passage').dataset.exerciseId === exercise, 'Panel and mode switching preserve exercise identity');
  assert(q('.feedback-snapshot').textContent.includes('Treat'), 'Treat Bag stays in the header');
  assert(d.documentElement.scrollWidth <= w.innerWidth + 1, 'Layout fits the viewport');
  choose(q('select[aria-label="Mode"]'), 'both');
  const selector = q('.interaction-selector');
  const columns = w.getComputedStyle(selector).gridTemplateColumns.split(' ').length;
  assert(w.innerWidth <= 760 ? columns === 2 : columns === 1, 'Selector is horizontal on phones and vertical on wide screens');
  return { assertions, width: w.innerWidth };
};
