/** Presentation checks; existing counting scenarios cover musical correctness. */
async function writingWorkspaceScenarios(w = window) {
  const d = w.document, results = [];
  const q = selector => d.querySelector(selector);
  const all = selector => [...d.querySelectorAll(selector)];
  const assert = (ok, label) => { if (!ok) throw new Error(label); results.push(label); };
  const settle = () => new Promise(resolve => w.setTimeout(resolve, 100));
  const choose = (selector, value) => { const input = q(selector); input.value = value; input.dispatchEvent(new w.Event('change', { bubbles: true })); };
  const fixture = async id => { choose('[data-preset]', id); await settle(); };
  const key = (target, value) => target.dispatchEvent(new w.KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true }));
  all('button').find(b => b.textContent === 'Counts').click();
  await fixture('dense-sixteenths');
  const scroll = q('.passage-scroll'), overview = q('.rhythm-overview');
  const targets = all('[data-count-id]');
  assert(!overview.hidden && scroll.scrollWidth > scroll.clientWidth, 'Dense score scrolls with overview');
  assert(targets.every(t => t.getBoundingClientRect().width >= 43 && t.getBoundingClientRect().height >= 43), 'Dense targets retain touch size on all widths');
  const heads = all('.passage-strip .notation ellipse');
  assert(heads.every((head, index) => {
    const note = head.getBoundingClientRect(), count = targets[index].getBoundingClientRect();
    return Math.abs(note.left + note.width / 2 - count.left - count.width / 2) < 1;
  }), 'Count targets align with their engraved noteheads across the passage');
  assert(overview.querySelectorAll('ellipse').length === q('.passage-strip').querySelectorAll('.notation ellipse').length, 'Overview depicts every written note');
  assert(!overview.querySelector('[tabindex], [data-event], [data-count-id]'), 'Miniature does not duplicate editor identities or focus targets');
  w.scrollTo(0, 0);
  targets[0].click(); key(d.activeElement, '1');
  assert(targets[0].textContent === '1' && d.activeElement === targets[1], 'Entry advances the active position');
  targets[35].click(); await settle();
  const bounds = scroll.getBoundingClientRect(), active = targets[35].getBoundingClientRect();
  assert(active.left >= bounds.left && active.right <= bounds.right, 'Forward selection reveals count locally');
  assert(w.scrollY === 0, 'Count selection does not scroll the page');
  const selectedScroll = scroll.scrollLeft;
  targets[35].click(); assert(Math.abs(scroll.scrollLeft - selectedScroll) < 1, 'Repeated selection does not drift');
  const windowRect = q('.rhythm-overview-window').getBoundingClientRect();
  assert(Math.abs(windowRect.width / overview.clientWidth - scroll.clientWidth / scroll.scrollWidth) < .01, 'Viewport width matches actual visible fraction');
  assert(Math.abs(parseFloat(q('.rhythm-overview-window').style.left) / 100 - scroll.scrollLeft / scroll.scrollWidth) < .001, 'Viewport position follows score scrolling');
  overview.focus({ preventScroll: true }); key(overview, 'End');
  assert(Math.abs(scroll.scrollLeft - (scroll.scrollWidth - scroll.clientWidth)) < 1, 'Overview End reaches passage end');
  key(overview, 'Home'); assert(scroll.scrollLeft === 0, 'Overview Home reaches passage start');
  key(overview, 'ArrowRight'); assert(scroll.scrollLeft > 0, 'Overview arrow navigation scrolls');
  scroll.scrollLeft = 123; await settle();
  assert(Number(overview.getAttribute('aria-valuenow')) === 123, 'Manual scroll synchronizes accessible overview value');
  all('button').find(b => b.textContent === 'Perform').click(); await settle();
  assert(!q('.passage').classList.contains('writing-workspace') && q('.passage').classList.contains('performance-workspace'), 'Performance uses the continuous score without editable count targets');
  const bars = all('.passage-strip .plan-measure').map(bar => bar.getBoundingClientRect());
  assert(bars.every(bar => Math.abs(bar.top - bars[0].top) < 1), 'Performance keeps four measures on one row above the input');
  assert(overview.hidden === (scroll.scrollWidth <= scroll.clientWidth + 1), 'Performance overview follows actual score overflow');
  if (!overview.hidden) { key(overview, 'End'); assert(scroll.scrollLeft > 0, 'Performance overview navigates the score'); }
  all('button').find(b => b.textContent === 'Counts').click(); await settle();
  const firstEmpty = targets[1].getBoundingClientRect(), writingBounds = scroll.getBoundingClientRect();
  assert(d.activeElement === targets[1] && firstEmpty.left >= writingBounds.left && firstEmpty.right <= writingBounds.right && targets[0].textContent === '1', 'Returning to writing reveals the first empty count and retains answers');
  targets[0].click(); key(d.activeElement, 'Delete'); assert(targets[0].textContent === '·', 'Deletion after returning to writing works');
  const action = all('.write-actions button').find(b => b.textContent === 'Check');
  assert(!scroll.contains(action) && q('.interaction-body').contains(action), 'Check remains outside scrolling music');
  const actionX = action.getBoundingClientRect().x;
  key(overview, 'End'); assert(action.getBoundingClientRect().x === actionX, 'Check does not drift with the score');
  const exercise = q('.passage').dataset.exerciseId;
  const selected = q('[data-counting-preference="dotted"]:checked');
  const setting = q(`[data-counting-preference="dotted"][value="${selected.value === 'true' ? 'false' : 'true'}"]`); setting.checked = true; setting.dispatchEvent(new w.Event('change', { bubbles: true }));
  assert(q('.passage').dataset.exerciseId === exercise && q('.exercise-summary').textContent.includes('Pending settings'), 'Pending settings preserve current exercise');
  await fixture('tie-across-bar');
  assert(q('.passage-ties [data-tie="across-bar"]') && (overview.hidden || overview.querySelector('path')), 'Cross-bar tie stays continuous with overview notation when needed');
  await fixture('whole');
  assert(overview.hidden === (scroll.scrollWidth <= scroll.clientWidth + 1), 'Simple exercise hides overview whenever it fits');
  if (w.innerWidth >= 390) assert(overview.hidden && scroll.scrollLeft === 0, 'Simple phone-sized passage fits without overview or movement');
  assert(d.documentElement.scrollWidth <= w.innerWidth, 'Horizontal scrolling stays inside passage');
  return { assertions: results.length, width: w.innerWidth, results };
}
